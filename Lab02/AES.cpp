using namespace std;

class AES {
public:
    using Byte = uint8_t;
    using Word = array<Byte, 4>;
    using State = array<array<Byte, 4>, 4>;
    using Block = array<Byte, 16>;

private:
    vector<Word> round_keys;
    int key_length;
    int nk, nr;


    // Bang S-box
    static const Byte s_box[256];
    static const Byte inv_s_box[256];



    // Doc byte theo thu tu cot
    State bytes_to_state(const Block& data) {
        State state{};

        for (int c = 0; c < 4; c++)
            for (int r = 0; r < 4; r++)
                state[r][c] = data[4 * c + r];

        return state;
    }

    // Chuyen state ve mang byte
    Block state_to_bytes(const State& state) {
        Block data{};

        for (int c = 0; c < 4; c++)
            for (int r = 0; r < 4; r++)
                data[4 * c + r] = state[r][c];

        return data;
    }

    // Nhan hai so trong truong GF(2^8)
    static Byte gmul(Byte a, Byte b) {
        Byte result = 0;

        for (int i = 0; i < 8; i++) {
            if (b & 1)
                result ^= a;

            bool high_bit = a & 0x80;
            a <<= 1;

            if (high_bit)
                a ^= 0x1B;

            b >>= 1;
        }

        return result;
    }

    // Xoay word sang trai mot byte
    Word rot_word(const Word& word) {
        return {word[1], word[2], word[3], word[0]};
    }

    // Thay tung byte bang S-box
    Word sub_word(const Word& word) {
        Word result{};

        for (int i = 0; i < 4; i++)
            result[i] = s_box[word[i]];

        return result;
    }

    // Tao khoa cho cac vong AES
    void key_expansion(const vector<Byte>& key) {
        nk = static_cast<int>(key.size()) / 4;
        nr = nk + 6;

        int total_words = 4 * (nr + 1);
        round_keys.clear();

        // Dua khoa goc vao dau danh sach
        for (int i = 0; i < nk; i++) {
            Word word{};

            for (int j = 0; j < 4; j++)
                word[j] = key[4 * i + j];

            round_keys.push_back(word);
        }

        Byte rcon = 1;

        for (int i = nk; i < total_words; i++) {
            Word temp = round_keys[i - 1];

            if (i % nk == 0) {
                temp = sub_word(rot_word(temp));
                temp[0] ^= rcon;

                // Cap nhat round constant
                rcon = gmul(rcon, 0x02);
            }
            else if (nk == 8 && i % nk == 4) {
                temp = sub_word(temp);
            }

            Word word{};

            for (int j = 0; j < 4; j++)
                word[j] = round_keys[i - nk][j] ^ temp[j];

            round_keys.push_back(word);
        }
    }

    // XOR state voi khoa cua vong
    void add_round_key(State& state, int round) {
        for (int c = 0; c < 4; c++)
            for (int r = 0; r < 4; r++)
                state[r][c] ^= round_keys[round * 4 + c][r];
    }

    // Thay byte bang S-box
    void sub_bytes(State& state) {
        for (auto& row : state)
            for (auto& byte : row)
                byte = s_box[byte];
    }

    // Thay byte bang inverse S-box
    void inv_sub_bytes(State& state) {
        for (auto& row : state)
            for (auto& byte : row)
                byte = inv_s_box[byte];
    }

    // Dich cac hang sang trai
    void shift_rows(State& state) {
        for (int r = 1; r < 4; r++) {
            array<Byte, 4> temp = state[r];

            for (int c = 0; c < 4; c++)
                state[r][c] = temp[(c + r) % 4];
        }
    }

    // Dich cac hang sang phai
    void inv_shift_rows(State& state) {
        for (int r = 1; r < 4; r++) {
            array<Byte, 4> temp = state[r];

            for (int c = 0; c < 4; c++)
                state[r][c] = temp[(c - r + 4) % 4];
        }
    }

    // Tron cac cot
    void mix_columns(State& state) {
        for (int c = 0; c < 4; c++) {
            Byte a = state[0][c];
            Byte b = state[1][c];
            Byte d = state[2][c];
            Byte e = state[3][c];

            state[0][c] = gmul(a, 2) ^ gmul(b, 3) ^ d ^ e;
            state[1][c] = a ^ gmul(b, 2) ^ gmul(d, 3) ^ e;
            state[2][c] = a ^ b ^ gmul(d, 2) ^ gmul(e, 3);
            state[3][c] = gmul(a, 3) ^ b ^ d ^ gmul(e, 2);
        }
    }

    // Tron cot khi giai ma
    void inv_mix_columns(State& state) {
        for (int c = 0; c < 4; c++) {
            Byte a = state[0][c];
            Byte b = state[1][c];
            Byte d = state[2][c];
            Byte e = state[3][c];

            state[0][c] = gmul(a, 14) ^ gmul(b, 11)
                        ^ gmul(d, 13) ^ gmul(e, 9);

            state[1][c] = gmul(a, 9) ^ gmul(b, 14)
                        ^ gmul(d, 11) ^ gmul(e, 13);

            state[2][c] = gmul(a, 13) ^ gmul(b, 9)
                        ^ gmul(d, 14) ^ gmul(e, 11);

            state[3][c] = gmul(a, 11) ^ gmul(b, 13)
                        ^ gmul(d, 9) ^ gmul(e, 14);
        }
    }

public:
    // Khoi tao AES voi khoa 128, 192 hoac 256 bit
    explicit AES(const vector<Byte>& key) {
        if (key.size() != 16 &&
            key.size() != 24 &&
            key.size() != 32) {
            throw invalid_argument("Khoa AES phai co 16, 24 hoac 32 byte");
        }

        key_length = static_cast<int>(key.size()) * 8;
        key_expansion(key);
    }

    // Ma hoa mot block 16 byte
    Block encrypt(const Block& plaintext) {
        State state = bytes_to_state(plaintext);

        add_round_key(state, 0);

        for (int round = 1; round < nr; round++) {
            sub_bytes(state);
            shift_rows(state);
            mix_columns(state);
            add_round_key(state, round);
        }

        sub_bytes(state);
        shift_rows(state);
        add_round_key(state, nr);

        return state_to_bytes(state);
    }

    // Giai ma mot block 16 byte
    Block decrypt(const Block& ciphertext) {
        State state = bytes_to_state(ciphertext);

        add_round_key(state, nr);

        for (int round = nr - 1; round > 0; round--) {
            inv_shift_rows(state);
            inv_sub_bytes(state);
            add_round_key(state, round);
            inv_mix_columns(state);
        }

        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, 0);

        return state_to_bytes(state);
    }

    int get_key_length() const {
        return key_length;
    }
};

